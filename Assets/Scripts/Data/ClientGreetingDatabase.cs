        // === МЕТОДЫ ===

        public string GetGreetingForRole(StaffController.Role role)
        {
            return role switch
            {
                StaffController.Role.Registrar => GetRandom(greetingsToRegistrar),
                StaffController.Role.Clerk => GetRandom(greetingsToClerk),
                StaffController.Role.Cashier => GetRandom(greetingsToCashier),
                StaffController.Role.Director => GetRandom(greetingsToDirector),
                _ => "Здравствуйте!"
            };
        }

        public string GetFarewell(bool isHappy, bool isEnraged, bool isSad)
        {
            if (isEnraged) return GetRandom(farewellsEnraged);
            if (isHappy) return GetRandom(farewellsHappy);
            if (isSad) return GetRandom(farewellsSad);
            return GetRandom(farewellsNeutral);
        }

        public string GetRandomSmallTalk()
        {
            var allTalk = new List<string>();
            allTalk.AddRange(smallTalkQueue);
            allTalk.AddRange(smallTalkWeather);
            allTalk.AddRange(smallTalkStaff);
            return GetRandom(allTalk);
        }

        private string GetRandom(List<string> list)
        {
            if (list == null || list.Count == 0) return "...";
            return list[Random.Range(0, list.Count)];
        }
