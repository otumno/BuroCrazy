namespace Managers
{
    /// <summary>
    /// Можно ли сейчас менять смены сотрудников. По ТЗ во время активного дня нельзя.
    /// Окно открыто, пока день не начат: на старте сессии и после ночного экрана планирования, до кнопки «Начать день».
    /// </summary>
    // Почему не проверка по периоду (ночь / не ночь): на старте сессии ночь длится 10 с и проходит, пока идёт туториал
    // или игрок сидит за столом, и тогда в первый день смены поменять было бы нельзя.
    // Статический класс, а не компонент: состояние живёт в рамках сессии и сбрасывается в GameSession.
    public static class ShiftPlanning
    {
        public static bool IsOpen { get; private set; }

        public static void Open() => IsOpen = true;

        public static void Close() => IsOpen = false;
    }
}
